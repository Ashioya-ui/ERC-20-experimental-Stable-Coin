#!/usr/bin/env python3
"""Generate high-precision reference values for SpectralMath tests.

Writes test/reference/ReferenceValues.sol. Pure standard library (decimal, 80 digits).
Run from the repository root:  python3 test/reference/gen_reference.py
"""
import random
from decimal import Decimal, getcontext

getcontext().prec = 80
WAD = Decimal(10) ** 18
LN8 = Decimal(8).ln()


def ln_wad(x: int) -> int:
    """round(ln(x / 1e18) * 1e18)"""
    v = (Decimal(x) / WAD).ln() * WAD
    return int(v.to_integral_value())


def hadamard8(v):
    x = list(v)
    h = 1
    while h < 8:
        for i in range(0, 8, 2 * h):
            for j in range(i, i + h):
                a, b = x[j], x[j + h]
                x[j], x[j + h] = a + b, a - b
        h *= 2
    return x


def entropy_wad(v) -> int:
    """Normalised Walsh spectral entropy of the raw (unnormalised) window, in WAD."""
    if max(v) == 0:
        return 0
    X = hadamard8(v)
    pw = [Decimal(t) * Decimal(t) for t in X]
    total = sum(pw)
    h = Decimal(0)
    for p in pw:
        if p == 0:
            continue
        q = p / total
        h -= q * q.ln()
    return int((h / LN8 * WAD).to_integral_value())


def main():
    rng = random.Random(0x5BEC7A)

    # ---- ln cases
    xs = [1, 2, 3, 10, 999, 10**6, 10**9, 10**12, 10**15, 10**17,
          125 * 10**15, 5 * 10**17, 707106781186547524, 707106781186547525,
          999999999999999999, 10**18, 10**18 + 1, 1414213562373095048,
          2 * 10**18, 2718281828459045235, 10**19, 10**24, 10**36, 10**50,
          2**128, 2**200, 2**255 - 1, 2**256 - 1]
    for _ in range(64):
        e = rng.uniform(0, 255.99)
        xs.append(max(1, int(2 ** e)))
    ln_rows = [(x, ln_wad(x)) for x in xs]

    # ---- entropy cases
    cases = []
    cases.append([7] * 8)
    cases.append([0, 0, 0, 0, 0, 0, 0, 5])
    cases.append([1, 0, 1, 0, 1, 0, 1, 0])
    cases.append([1, 0, 0, 0, 1, 0, 0, 0])
    cases.append([1, 2, 3, 4, 5, 6, 7, 8])
    cases.append([10**18, 10**18, 10**18, 10**18, 10**18, 10**18, 10**18, 50 * 10**18])
    cases.append([2**128 - 1, 1, 2**128 - 1, 1, 2**128 - 1, 1, 2**128 - 1, 1])
    for _ in range(25):
        kind = rng.randrange(4)
        if kind == 0:   # uniform noise
            v = [rng.randrange(0, 10**24) for _ in range(8)]
        elif kind == 1:  # calm flow with one whale
            base = rng.randrange(10**18, 10**20)
            v = [base + rng.randrange(0, base // 10) for _ in range(8)]
            v[rng.randrange(8)] = base * rng.randrange(20, 1000)
        elif kind == 2:  # sparse
            v = [0] * 8
            for _ in range(rng.randrange(1, 4)):
                v[rng.randrange(8)] = rng.randrange(1, 2**120)
        else:            # near-constant
            base = rng.randrange(10**20, 10**22)
            v = [base + rng.randrange(-base // 1000, base // 1000) for _ in range(8)]
        cases.append(v)
    ent_rows = [(v, entropy_wad(v)) for v in cases]

    out = []
    out.append("// SPDX-License-Identifier: MIT")
    out.append("pragma solidity ^0.8.26;")
    out.append("")
    out.append("// AUTO-GENERATED by test/reference/gen_reference.py (Python decimal, 80 digits).")
    out.append("// Do not edit by hand.")
    out.append("library ReferenceValues {")
    out.append(f"    uint256 internal constant LN_CASES = {len(ln_rows)};")
    out.append(f"    uint256 internal constant ENTROPY_CASES = {len(ent_rows)};")
    out.append("")
    out.append("    /// @return x input (WAD)  @return y round(ln(x / 1e18) * 1e18)")
    out.append("    function lnCase(uint256 i) internal pure returns (uint256 x, int256 y) {")
    for i, (x, y) in enumerate(ln_rows):
        kw = "if" if i == 0 else "else if"
        out.append(f"        {kw} (i == {i}) return ({x}, {y});")
    out.append("        revert(\"no case\");")
    out.append("    }")
    out.append("")
    out.append("    /// @return v window  @return h round(H_WHT * 1e18)")
    out.append("    function entropyCase(uint256 i) internal pure returns (uint256[8] memory v, uint256 h) {")
    for i, (v, h) in enumerate(ent_rows):
        kw = "if" if i == 0 else "else if"
        vv = ", ".join(str(t) for t in v)
        out.append(f"        {kw} (i == {i}) return ([uint256({v[0]}), " + ", ".join(str(t) for t in v[1:]) + f"], {h});")
    out.append("        revert(\"no case\");")
    out.append("    }")
    out.append("}")
    path = "test/reference/ReferenceValues.sol"
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {path}: {len(ln_rows)} ln cases, {len(ent_rows)} entropy cases")
    # print a few for the record
    for v, h in ent_rows[:5]:
        print(v, h)


if __name__ == "__main__":
    main()
